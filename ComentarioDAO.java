import java.sql.*;
import java.util.*;

public class ComentarioDAO {
    public ComentarioDAO(){ // Compatível com o banco de versões anteriores.
        try(Connection c=ConexaoBanco.getConexao();Statement s=c.createStatement()){
            s.execute("CREATE TABLE IF NOT EXISTS comentario (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "filme_id INT, resposta_a INT DEFAULT 0, curtidas INT DEFAULT 0, " +
                "titulo_filme VARCHAR(255),autor VARCHAR(255),texto CLOB, autor_id INT)");
            s.execute("ALTER TABLE comentario ADD COLUMN IF NOT EXISTS autor_id INT");
        }catch(SQLException e){throw new IllegalStateException("Comentários: "+e.getMessage(),e);}
    }
    public boolean inserir(Comentario c) {
        String sql="INSERT INTO comentario(filme_id,resposta_a,curtidas,titulo_filme,autor,texto,autor_id) VALUES(?,?,?,?,?,?,?)";
        try(Connection con=ConexaoBanco.getConexao();PreparedStatement p=con.prepareStatement(sql)){
            p.setInt(1,c.getFilmeId());p.setInt(2,c.getRespostaA());p.setInt(3,0);
            p.setString(4,c.getTituloFilme());p.setString(5,c.getAutor());
            p.setString(6,c.getTexto());
            if(c.getAutorId()>0)p.setInt(7,c.getAutorId());else p.setNull(7,Types.INTEGER);
            return p.executeUpdate()==1;
        }catch(SQLException e){System.err.println("Comentário: "+e.getMessage());return false;}
    }
    public List<Comentario> listarPorFilme(int filmeId){
        List<Comentario> lista=new ArrayList<>();
        try(Connection c=ConexaoBanco.getConexao();
            PreparedStatement p=c.prepareStatement("SELECT * FROM comentario WHERE filme_id=? ORDER BY id")){
            p.setInt(1,filmeId);
            try(ResultSet r=p.executeQuery()){
                while(r.next()){
                    Comentario co=new Comentario(r.getInt("id"),r.getInt("resposta_a"),
                        r.getInt("curtidas"),r.getString("titulo_filme"),
                        r.getString("autor"),r.getString("texto"));
                    co.setFilmeId(r.getInt("filme_id"));co.setAutorId(r.getInt("autor_id"));
                    lista.add(co);
                }
            }
        }catch(SQLException e){System.err.println("Listar comentários: "+e.getMessage());}
        return lista;
    }
    /** Cada conta só pode curtir um comentário uma vez. */
    public boolean curtir(int comentarioId,int usuarioId){
        if(usuarioId<=0)return false;
        try(Connection c=ConexaoBanco.getConexao()){
            c.setAutoCommit(false);
            try(PreparedStatement p=c.prepareStatement(
                "INSERT INTO curtida_comentario(usuario_id,comentario_id) VALUES(?,?)")){
                p.setInt(1,usuarioId);p.setInt(2,comentarioId);p.executeUpdate();
            }
            try(PreparedStatement p=c.prepareStatement(
                "UPDATE comentario SET curtidas=curtidas+1 WHERE id=?")){
                p.setInt(1,comentarioId);p.executeUpdate();
            }
            c.commit();return true;
        }catch(SQLException e){return false;}
    }
    /** Compatibilidade: comentários legados sem conta não podem receber curtidas anônimas. */
    public void curtir(int comentarioId){
        if(Sessao.ativa())curtir(comentarioId,Sessao.getUsuario().getId());
    }
    public boolean limparMeusPorFilme(int filmeId,int usuarioId) {
        if(usuarioId<=0)return false;
        try(Connection c=ConexaoBanco.getConexao()){
            c.setAutoCommit(false);
            List<Integer> meus=new ArrayList<>();
            try(PreparedStatement p=c.prepareStatement(
                "SELECT id FROM comentario WHERE filme_id=? AND autor_id=?")){
                p.setInt(1,filmeId);p.setInt(2,usuarioId);
                try(ResultSet r=p.executeQuery()){while(r.next())meus.add(r.getInt(1));}
            }
            for(int id:meus) {
                // Remove as curtidas do próprio comentário e das respostas a ele.
                try(PreparedStatement p=c.prepareStatement(
                    "DELETE FROM curtida_comentario WHERE comentario_id IN " +
                    "(SELECT id FROM comentario WHERE id=? OR resposta_a=?)")){
                    p.setInt(1,id);p.setInt(2,id);p.executeUpdate();
                }
                try(PreparedStatement p=c.prepareStatement("DELETE FROM comentario WHERE resposta_a=?")){
                    p.setInt(1,id);p.executeUpdate();
                }
                try(PreparedStatement p=c.prepareStatement("DELETE FROM comentario WHERE id=?")){
                    p.setInt(1,id);p.executeUpdate();
                }
            }
            c.commit();return true;
        }catch(SQLException e){System.err.println("Limpeza: "+e.getMessage());return false;}
    }
    /** Operação administrativa legada, não usada pela interface pública. */
    public void limparPorFilme(int filmeId){
        try(Connection c=ConexaoBanco.getConexao()){
            c.setAutoCommit(false);
            try(PreparedStatement p=c.prepareStatement(
                "DELETE FROM curtida_comentario WHERE comentario_id IN (SELECT id FROM comentario WHERE filme_id=?)")){
                p.setInt(1,filmeId);p.executeUpdate();
            }
            try(PreparedStatement p=c.prepareStatement("DELETE FROM comentario WHERE filme_id=?")){
                p.setInt(1,filmeId);p.executeUpdate();
            }
            c.commit();
        }catch(SQLException e){System.err.println("Limpeza: "+e.getMessage());}
    }
}

import java.sql.*;

public class ConexaoBanco {
    private static final String URL = "jdbc:h2:" +
            System.getProperty("cinematch.banco", "./banco/cinematch") + ";AUTO_SERVER=TRUE";
    private static final String USUARIO = "sa";
    private static final String SENHA = "";

    public static Connection getConexao() throws SQLException {
        return DriverManager.getConnection(URL, USUARIO, SENHA);
    }

    public static void inicializarBanco() {
        new java.io.File("banco").mkdirs();
        try (Connection c = getConexao(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS usuario (" +
                "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "nome VARCHAR(100) NOT NULL, email VARCHAR(150) UNIQUE NOT NULL, " +
                "senha VARCHAR(255) NOT NULL, idade INT, bio CLOB, intencao VARCHAR(60))");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS nascimento DATE");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS identidade_genero VARCHAR(90)");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS orientacao VARCHAR(90)");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS interesse VARCHAR(90)");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS mostrar_informacoes BOOLEAN DEFAULT FALSE");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS permitir_sugestoes BOOLEAN DEFAULT TRUE");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS generos_favoritos VARCHAR(1200)");
            s.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS foto VARCHAR(1000)");
            s.execute("CREATE TABLE IF NOT EXISTS filme (" +
                "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "titulo VARCHAR(180) NOT NULL, genero VARCHAR(100), ano INT, " +
                "capa VARCHAR(300), curtidas INT DEFAULT 0, nota INT DEFAULT 0)");
            s.execute("ALTER TABLE filme ADD COLUMN IF NOT EXISTS diretor VARCHAR(180)");
            s.execute("CREATE TABLE IF NOT EXISTS preferencia_filme (" +
                "usuario_id INT NOT NULL, filme_id INT NOT NULL, " +
                "curtiu BOOLEAN DEFAULT FALSE, salvo BOOLEAN DEFAULT FALSE, " +
                "PRIMARY KEY (usuario_id, filme_id), " +
                "FOREIGN KEY (usuario_id) REFERENCES usuario(id), " +
                "FOREIGN KEY (filme_id) REFERENCES filme(id))");
            s.execute("CREATE TABLE IF NOT EXISTS conexao (" +
                "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "solicitante_id INT NOT NULL, destinatario_id INT NOT NULL, " +
                "status VARCHAR(20) DEFAULT 'PENDENTE', " +
                "UNIQUE (solicitante_id, destinatario_id), " +
                "FOREIGN KEY (solicitante_id) REFERENCES usuario(id), " +
                "FOREIGN KEY (destinatario_id) REFERENCES usuario(id))");
            s.execute("CREATE TABLE IF NOT EXISTS comentario (" +
                "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "filme_id INT, resposta_a INT DEFAULT 0, curtidas INT DEFAULT 0, " +
                "titulo_filme VARCHAR(255), autor VARCHAR(255), texto CLOB)");
            s.execute("ALTER TABLE comentario ADD COLUMN IF NOT EXISTS autor_id INT");
            s.execute("CREATE TABLE IF NOT EXISTS curtida_comentario (" +
                "usuario_id INT NOT NULL, comentario_id INT NOT NULL, " +
                "PRIMARY KEY (usuario_id, comentario_id), " +
                "FOREIGN KEY (usuario_id) REFERENCES usuario(id), " +
                "FOREIGN KEY (comentario_id) REFERENCES comentario(id))");
        } catch (SQLException e) {
            throw new IllegalStateException("Falha ao preparar banco H2: " + e.getMessage(), e);
        }
        new FilmeDAO().sincronizarCatalogo();
    }
}
